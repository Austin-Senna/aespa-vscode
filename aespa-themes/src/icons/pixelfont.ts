export const GLYPH_WIDTH = 3;
export const GLYPH_HEIGHT = 5;
export const GLYPH_GAP = 1;

export function hasGlyph(ch: string): boolean {
  return ch in GLYPHS;
}

/** Width in pixel units of a label, including inter-glyph gaps. */
export function labelWidth(label: string): number {
  const n = [...label].length;
  return n * GLYPH_WIDTH + Math.max(0, n - 1) * GLYPH_GAP;
}

/**
 * Render a label as a single SVG path of unit squares, with its top-left at
 * (x, y) and each pixel `scale` user units wide.
 */
export function labelPath(label: string, x: number, y: number, scale: number): string {
  const parts: string[] = [];
  let cursor = 0;
  for (const ch of [...label]) {
    const glyph = GLYPHS[ch];
    if (!glyph) {
      throw new Error(`No glyph for ${JSON.stringify(ch)} in label ${JSON.stringify(label)}`);
    }
    glyph.forEach((row, ry) => {
      [...row].forEach((bit, rx) => {
        if (bit === "1") {
          const px = x + (cursor + rx) * scale;
          const py = y + ry * scale;
          parts.push(`M${trim(px)} ${trim(py)}h${trim(scale)}v${trim(scale)}h-${trim(scale)}z`);
        }
      });
    });
    cursor += GLYPH_WIDTH + GLYPH_GAP;
  }
  return parts.join("");
}

function trim(n: number): string {
  return Number(n.toFixed(3)).toString();
}
