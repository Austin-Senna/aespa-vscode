/**
 * Extract the "æ" outline from Cormorant Garamond Italic (SIL OFL 1.1) into
 * src/icons/glyphs/ae.ts as path data in a 0..20 box. Run once; output is committed.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import opentype from "opentype.js";

const FONT = resolve(import.meta.dirname, "../node_modules/@fontsource/cormorant-garamond/files/cormorant-garamond-latin-600-italic.woff");
const OUT = resolve(import.meta.dirname, "../src/icons/glyphs/ae.ts");

const buffer = readFileSync(FONT);
const font = opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
const glyph = font.charToGlyph("æ");
const path = glyph.getPath(0, 0, 100);
const box = path.getBoundingBox();
const w = box.x2 - box.x1;
const h = box.y2 - box.y1;
const scale = 18 / Math.max(w, h);
const ox = (20 - w * scale) / 2 - box.x1 * scale;
const oy = (20 - h * scale) / 2 - box.y1 * scale;
const fitted = glyph.getPath(0, 0, 100);
for (const cmd of fitted.commands as unknown as Array<Record<string, number | string | undefined>>) {
  for (const k of ["x", "y", "x1", "y1", "x2", "y2"]) {
    const v = cmd[k];
    if (typeof v === "number") {
      cmd[k] = Number(((k.startsWith("x") ? ox : oy) + v * scale).toFixed(2));
    }
  }
}
const d = fitted.toPathData(2);
writeFileSync(OUT, `// Generated by scripts/ae-glyph.ts from Cormorant Garamond Italic 600 (SIL OFL 1.1). Do not edit.
import type { Glyph } from "./types.js";

export const AE_GLYPH: Glyph = {
  id: "ae",
  d: "${d}",
};
`);
console.log(`æ: ${fitted.commands.length} commands, ${d.length} chars -> ${OUT}`);
