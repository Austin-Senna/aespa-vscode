/** Regenerate src/icons/glyphs/items/index.ts from the files in that directory. Deterministic. */
import { readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const dir = resolve(import.meta.dirname, "../src/icons/glyphs/items");
const files = readdirSync(dir).filter((n) => n.endsWith(".ts") && n !== "index.ts").sort();
const lines = files.map((f, i) => `import { GLYPH as g${i} } from "./${f.replace(/\.ts$/, ".js")}";`);
const body = `// Generated by scripts/glyph-barrel.ts. Do not edit; run \`npm run glyphs:barrel\`.
import type { Glyph } from "../types.js";
${lines.join("\n")}

export const ITEMS: Glyph[] = [${files.map((_, i) => `g${i}`).join(", ")}];
`;
writeFileSync(resolve(dir, "index.ts"), body);
console.log(`${files.length} items`);
